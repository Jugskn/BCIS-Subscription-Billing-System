import { createRequire } from "node:module";
import path from "node:path";
import ExcelJS from "exceljs";
import pdfmake from "pdfmake";
import { formatCentavos } from "@bcis/shared";
import type { ExportFormat } from "@bcis/shared";

const require = createRequire(import.meta.url);

export type ReportColumn = {
  key: string;
  header: string;
  align?: "left" | "right";
  /** When true, cell values are centavos strings/numbers formatted to pesos at output. */
  money?: boolean;
};

export type ReportExportInput = {
  title: string;
  generatedBy: string;
  filters: Record<string, string | undefined | null>;
  columns: ReportColumn[];
  rows: Array<Record<string, string | number | null | undefined>>;
  /** Totals keyed by column key; money columns are centavos strings. */
  totals?: Record<string, string | number | null | undefined>;
  filenameBase: string;
  /** Company name from settings (header). Defaults to BCIS. */
  companyName?: string;
};

export type ExportResult = {
  buffer: Buffer;
  contentType: string;
  filename: string;
};

function ensurePdfFonts() {
  const fonts = pdfmake as unknown as {
    fonts?: unknown;
    setFonts: (f: unknown) => void;
    setLocalAccessPolicy: (cb: (p: string) => boolean) => void;
    setUrlAccessPolicy: (cb: (u: string) => boolean) => void;
  };
  if (!fonts.fonts) {
    const roboto = require("pdfmake/fonts/Roboto.js") as Record<
      string,
      Record<string, string>
    >;
    fonts.setFonts(roboto);
    // Font files live under node_modules/pdfmake/fonts — allow local reads for those only.
    fonts.setLocalAccessPolicy((filePath) => {
      const normalized = path.normalize(filePath).toLowerCase();
      return (
        normalized.includes(`${path.sep}pdfmake${path.sep}`) ||
        normalized.includes("/pdfmake/")
      );
    });
    fonts.setUrlAccessPolicy(() => false);
  }
}

function formatCell(
  col: ReportColumn,
  value: string | number | null | undefined,
): string {
  if (value === null || value === undefined || value === "") return "";
  if (col.money) {
    try {
      return formatCentavos(BigInt(String(value)));
    } catch {
      return String(value);
    }
  }
  return String(value);
}

function filterLines(filters: ReportExportInput["filters"]): string[] {
  return Object.entries(filters)
    .filter(([, v]) => v !== undefined && v !== null && String(v).length > 0)
    .map(([k, v]) => `${k}: ${v}`);
}

function stamp(): string {
  return new Date().toISOString().replace(/[:.]/g, "-").slice(0, 19);
}

export function buildCsv(input: ReportExportInput): ExportResult {
  const lines: string[] = [];
  const escape = (s: string) => {
    if (/[",\n]/.test(s)) return `"${s.replace(/"/g, '""')}"`;
    return s;
  };
  lines.push(escape(input.companyName?.trim() || "BCIS"));
  lines.push(escape(input.title));
  for (const f of filterLines(input.filters)) lines.push(escape(f));
  lines.push(escape(`Generated by: ${input.generatedBy}`));
  lines.push(escape(`Generated at: ${new Date().toISOString()}`));
  lines.push("");
  lines.push(input.columns.map((c) => escape(c.header)).join(","));
  for (const row of input.rows) {
    lines.push(
      input.columns.map((c) => escape(formatCell(c, row[c.key]))).join(","),
    );
  }
  if (input.totals) {
    lines.push(
      input.columns
        .map((c, i) => {
          if (i === 0 && input.totals![c.key] === undefined) return escape("TOTAL");
          return escape(formatCell(c, input.totals![c.key]));
        })
        .join(","),
    );
  }
  const buffer = Buffer.from(lines.join("\r\n"), "utf8");
  return {
    buffer,
    contentType: "text/csv; charset=utf-8",
    filename: `${input.filenameBase}-${stamp()}.csv`,
  };
}

export async function buildXlsx(input: ReportExportInput): Promise<ExportResult> {
  const wb = new ExcelJS.Workbook();
  wb.creator = "BCIS";
  const ws = wb.addWorksheet("Report", {
    views: [{ state: "frozen", ySplit: 1 }],
  });

  ws.addRow([input.companyName?.trim() || "BCIS"]);
  ws.addRow([input.title]);
  for (const f of filterLines(input.filters)) ws.addRow([f]);
  ws.addRow([`Generated by: ${input.generatedBy}`]);
  ws.addRow([`Generated at: ${new Date().toLocaleString("en-PH")}`]);
  ws.addRow([]);

  const header = ws.addRow(input.columns.map((c) => c.header));
  header.font = { bold: true };

  for (const row of input.rows) {
    const excelRow = ws.addRow(
      input.columns.map((c) => formatCell(c, row[c.key])),
    );
    input.columns.forEach((c, i) => {
      if (c.align === "right" || c.money) {
        excelRow.getCell(i + 1).alignment = { horizontal: "right" };
      }
    });
  }

  if (input.totals) {
    const totalRow = ws.addRow(
      input.columns.map((c, i) => {
        if (i === 0 && input.totals![c.key] === undefined) return "TOTAL";
        return formatCell(c, input.totals![c.key]);
      }),
    );
    totalRow.font = { bold: true };
    input.columns.forEach((c, i) => {
      if (c.align === "right" || c.money) {
        totalRow.getCell(i + 1).alignment = { horizontal: "right" };
      }
    });
  }

  input.columns.forEach((c, i) => {
    ws.getColumn(i + 1).width = Math.max(12, c.header.length + 2);
  });

  const arrayBuffer = await wb.xlsx.writeBuffer();
  const buffer = Buffer.from(arrayBuffer);
  return {
    buffer,
    contentType:
      "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
    filename: `${input.filenameBase}-${stamp()}.xlsx`,
  };
}

export async function buildPdf(input: ReportExportInput): Promise<ExportResult> {
  ensurePdfFonts();

  const generatedAt = new Date().toLocaleString("en-PH");
  const filters = filterLines(input.filters);

  type Cell = {
    text: string;
    style?: string;
    bold?: boolean;
    alignment?: "left" | "right";
  };
  const body: Cell[][] = [
    input.columns.map((c) => ({
      text: c.header,
      style: "tableHeader",
      alignment: (c.align === "right" || c.money ? "right" : "left") as
        | "left"
        | "right",
    })),
  ];

  for (const row of input.rows) {
    body.push(
      input.columns.map((c) => ({
        text: formatCell(c, row[c.key]),
        alignment: (c.align === "right" || c.money ? "right" : "left") as
          | "left"
          | "right",
      })),
    );
  }

  if (input.totals) {
    body.push(
      input.columns.map((c, i) => ({
        text:
          i === 0 && input.totals![c.key] === undefined
            ? "TOTAL"
            : formatCell(c, input.totals![c.key]),
        bold: true,
        alignment: (c.align === "right" || c.money ? "right" : "left") as
          | "left"
          | "right",
      })),
    );
  }

  const docDefinition = {
    pageMargins: [40, 60, 40, 50] as [number, number, number, number],
    header: {
      margin: [40, 20, 40, 0] as [number, number, number, number],
      stack: [
        { text: input.companyName?.trim() || "BCIS", style: "brand" },
        { text: input.title, style: "title" },
        {
          text: filters.length ? filters.join("  |  ") : "No filters",
          style: "meta",
        },
        {
          text: `Generated by ${input.generatedBy}  ·  ${generatedAt}`,
          style: "meta",
        },
      ],
    },
    footer: (currentPage: number, pageCount: number) => ({
      margin: [40, 0, 40, 20] as [number, number, number, number],
      text: `Page ${currentPage} of ${pageCount}`,
      alignment: "center" as const,
      fontSize: 9,
      color: "#6B6B6B",
    }),
    content: [
      {
        table: {
          headerRows: 1,
          widths: input.columns.map(() => "*"),
          body,
        },
        layout: {
          hLineWidth: () => 0.5,
          vLineWidth: () => 0,
          hLineColor: () => "#E7E5E4",
          paddingLeft: () => 4,
          paddingRight: () => 4,
          paddingTop: () => 4,
          paddingBottom: () => 4,
        },
      },
    ],
    styles: {
      brand: { fontSize: 11, bold: true, color: "#7A1F2B" },
      title: {
        fontSize: 14,
        bold: true,
        margin: [0, 2, 0, 2] as [number, number, number, number],
      },
      meta: {
        fontSize: 9,
        color: "#6B6B6B",
        margin: [0, 1, 0, 0] as [number, number, number, number],
      },
      tableHeader: { bold: true, fontSize: 10, color: "#111111" },
    },
    defaultStyle: { font: "Roboto", fontSize: 9 },
  };

  const pdf = pdfmake.createPdf(docDefinition as never);
  const buffer = await pdf.getBuffer();
  return {
    buffer,
    contentType: "application/pdf",
    filename: `${input.filenameBase}-${stamp()}.pdf`,
  };
}

export async function exportReport(
  format: ExportFormat,
  input: ReportExportInput,
): Promise<ExportResult> {
  if (format === "csv") return buildCsv(input);
  if (format === "xlsx") return buildXlsx(input);
  return buildPdf(input);
}
